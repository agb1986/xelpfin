/**
 * The ISO 639-2 language code table with English display names, from the Library of
 * Congress registration authority list at
 * https://www.loc.gov/standards/iso639-2/ISO-639-2_utf-8.txt (fields: bibliographic code,
 * terminologic code, ISO 639-1 code, English name, French name). The `qaa-qtz` range
 * reserved for local use is left out; every other row is kept, including the collective
 * and special codes (`mis`, `mul`, `und`, `zxx`).
 *
 * Data only: the picker list and the code matching live in settings.ts.
 */
export interface Language {
  /** ISO 639-2/B (bibliographic) code, the canonical value stored in settings. */
  code: string;
  /** ISO 639-2/T (terminologic) code, only when it differs from the B code. */
  terminologic?: string;
  /** ISO 639-1 two-letter code, when the language has one. */
  alpha2?: string;
  /** English name as published; alternatives are separated by "; ". */
  name: string;
}

